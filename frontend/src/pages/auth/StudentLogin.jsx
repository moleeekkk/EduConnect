import React, { useState } from "react";
import { useNavigate } from "react-router-dom";
import { GraduationCap, ArrowLeft, ArrowRight, KeyRound, Smartphone } from "lucide-react";
import AuthLayout from "../../layouts/AuthLayout";
import Button from "../../components/common/Button";
import Input from "../../components/common/Input";
import { authApi } from "../../services/api";

const StudentLogin = () => {
  const navigate = useNavigate();
  const [enrollmentNo, setEnrollmentNo] = useState("");
  const [error, setError] = useState("");
  const [isLoading, setIsLoading] = useState(false);

  const handleSubmit = async (e) => {
    e.preventDefault();
    const cleanNo = enrollmentNo.trim().toUpperCase();
    if (!cleanNo) {
      setError("Please enter your registered Enrollment Number");
      return;
    }

    if (cleanNo.length < 4) {
      setError("Enrollment Number must be at least 4 characters long");
      return;
    }

    setError("");
    setIsLoading(true);

    try {
      const res = await authApi.sendStudentOtp(cleanNo);
      setIsLoading(false);
      navigate("/verify-otp", {
        state: {
          enrollmentNo: cleanNo,
          maskedPhone: res.maskedPhone || "+91 98*** **421",
        },
      });
    } catch (err) {
      setIsLoading(false);
      // Fallback for offline testing
      navigate("/verify-otp", {
        state: {
          enrollmentNo: cleanNo,
          maskedPhone: "+91 98*** **421",
        },
      });
    }
  };

  return (
    <AuthLayout>
      <div className="bg-white rounded-3xl p-8 border border-[#E2E8F0] shadow-xl shadow-slate-200/50">
        {/* Back Link */}
        <button
          onClick={() => navigate("/")}
          className="inline-flex items-center gap-1.5 text-xs font-semibold text-[#64748B] hover:text-[#2563EB] transition-colors mb-6 cursor-pointer"
        >
          <ArrowLeft className="w-4 h-4" /> Back to Role Selection
        </button>

        {/* Header Icon & Title */}
        <div className="text-center mb-6">
          <div className="w-14 h-14 rounded-2xl bg-[#2563EB]/10 text-[#2563EB] flex items-center justify-center mx-auto mb-3">
            <GraduationCap className="w-8 h-8" />
          </div>
          <span className="inline-block px-3 py-1 rounded-full bg-[#2563EB]/10 text-[#2563EB] text-xs font-bold mb-2">
            Student Portal
          </span>
          <h1 className="text-2xl font-bold text-[#1E293B]">Student Login</h1>
          <p className="text-xs text-[#64748B] mt-1">
            Enter your Enrollment Number to receive an OTP code on your registered email/phone.
          </p>
        </div>

        {/* Login Form */}
        <form onSubmit={handleSubmit}>
          <Input
            label="Enrollment Number"
            placeholder="e.g. 2024MCA001"
            value={enrollmentNo}
            onChange={(e) => {
              setEnrollmentNo(e.target.value.toUpperCase());
              if (error) setError("");
            }}
            icon={KeyRound}
            error={error}
            required
            helperText="Format: 2024MCA001, STU202401, etc."
          />

          <div className="p-3.5 rounded-xl bg-[#F8FAFC] border border-[#E2E8F0] mb-6 flex items-start gap-3">
            <Smartphone className="w-5 h-5 text-[#14B8A6] flex-shrink-0 mt-0.5" />
            <p className="text-xs text-[#64748B] leading-relaxed">
              An OTP code will be generated by the Spring Boot backend and dispatched to your email/phone.
            </p>
          </div>

          <Button
            type="submit"
            variant="primary"
            isLoading={isLoading}
            icon={ArrowRight}
            className="w-full"
          >
            Send Real OTP Code
          </Button>
        </form>

        {/* Demo Helper Box */}
        <div className="mt-6 pt-4 border-t border-[#E2E8F0] text-center text-xs text-[#64748B]">
          <p className="font-semibold text-[#1E293B]">Demo Enrollment Number:</p>
          <code className="bg-[#F8FAFC] text-[#2563EB] px-2 py-0.5 rounded font-mono border border-[#E2E8F0] text-[11px] inline-block mt-1">
            2024MCA001
          </code>
        </div>
      </div>
    </AuthLayout>
  );
};

export default StudentLogin;
